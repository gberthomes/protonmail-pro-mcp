/**
 * Adapter for the internal gRPC interface of the official Proton Mail Bridge.
 *
 * This is the only module that knows the wire protocol. It connects over the
 * Unix socket announced in Bridge's grpcServerConfig.json, pins the
 * self-signed certificate published in the same file (no "accept any
 * certificate"), and sends the server token as gRPC metadata.
 *
 * Before connecting it checks that the config file and the socket belong to
 * the expected user and cannot be replaced by someone else: a forged socket
 * would otherwise receive the token.
 */

import { X509Certificate } from 'node:crypto';
import { EventEmitter } from 'node:events';
import { lstatSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as grpc from '@grpc/grpc-js';
import * as protoLoader from '@grpc/proto-loader';

const PROTO = fileURLToPath(new URL('./proto/bridge-control.proto', import.meta.url));
const PROTO_SRC = fileURLToPath(new URL('../../src/bridge-manager/proto/bridge-control.proto', import.meta.url));

export interface GrpcServerConfig {
  port: number;
  cert: string;
  token: string;
  fileSocketPath: string;
}

export type BridgeUserState = 'SIGNED_OUT' | 'LOCKED' | 'CONNECTED';

export interface BridgeUser {
  id: string;
  username: string;
  state: BridgeUserState;
  splitMode: boolean;
  usedBytes: number;
  totalBytes: number;
  addresses: string[];
  /** IMAP/SMTP password generated by Bridge for this account. Secret: never log it. */
  password: string;
}

export interface MailServerSettings {
  imapPort: number;
  smtpPort: number;
  useSSLForImap: boolean;
  useSSLForSmtp: boolean;
}

/** Normalised Bridge events (see bridge-control.proto for the subset decoded). */
export type BridgeEvent =
  | { kind: 'login'; type: 'error'; errorType: string; message: string }
  | { kind: 'login'; type: 'tfaRequested' | 'twoPasswordRequested' | 'fidoRequested' | 'tfaOrFidoRequested' | 'fidoTouchRequested' | 'fidoTouchCompleted' | 'fidoPinRequired'; username: string }
  | { kind: 'login'; type: 'finished' | 'alreadyLoggedIn'; userId: string; wasSignedOut: boolean }
  | { kind: 'login'; type: 'hvRequested'; hvUrl: string }
  | { kind: 'user'; type: 'disconnected' | 'imapLoginFailed'; username: string }
  | { kind: 'user'; type: 'changed' | 'syncStarted' | 'syncFinished' | 'splitModeChanged'; userId: string }
  | { kind: 'user'; type: 'bad'; userId: string; message: string }
  | { kind: 'user'; type: 'syncProgress'; userId: string; progress: number; remainingMs: number }
  | { kind: 'app'; type: 'internetStatus'; connected: boolean }
  | { kind: 'app'; type: 'allUsersLoaded' }
  | { kind: 'keychain'; type: 'hasNoKeychain' | 'changeKeychainFinished' | 'rebuildKeychain' }
  | { kind: 'mailServer'; type: 'error'; errorType: string }
  | { kind: 'mailServer'; type: 'changed'; settings: MailServerSettings }
  | { kind: 'mailServer'; type: 'changeFinished' }
  | { kind: 'genericError'; code: number };

export class BridgeSecurityError extends Error {}

// ---------------------------------------------------------------------------- file trust checks

export interface TrustOptions {
  /** Expected owner of Bridge's files (defaults to the current user). */
  uid?: number;
}

function expectedUid(opts: TrustOptions): number | undefined {
  return opts.uid ?? (typeof process.getuid === 'function' ? process.getuid() : undefined);
}

/** A directory is safe when only its owner can write to it (or it is sticky, like /tmp). */
function checkDir(path: string, uid: number | undefined, label: string): void {
  const st = statSync(path);
  if (!st.isDirectory()) throw new BridgeSecurityError(`${label} ${path} is not a directory`);
  const writableByOthers = (st.mode & 0o022) !== 0;
  const sticky = (st.mode & 0o1000) !== 0;
  if (writableByOthers && !sticky) throw new BridgeSecurityError(`${label} ${path} is writable by other users`);
  if (!writableByOthers && uid !== undefined && st.uid !== uid && st.uid !== 0) {
    throw new BridgeSecurityError(`${label} ${path} is owned by uid ${st.uid}, expected ${uid}`);
  }
}

/** Read grpcServerConfig.json after checking who can have written it. */
export function readServerConfig(path: string, opts: TrustOptions = {}): GrpcServerConfig {
  const uid = expectedUid(opts);
  const st = lstatSync(path);
  if (!st.isFile()) throw new BridgeSecurityError(`${path} is not a regular file`);
  if (uid !== undefined && st.uid !== uid) throw new BridgeSecurityError(`${path} is owned by uid ${st.uid}, expected ${uid}`);
  if ((st.mode & 0o022) !== 0) throw new BridgeSecurityError(`${path} is writable by other users`);
  checkDir(dirname(path), uid, 'Bridge settings directory');
  const cfg = JSON.parse(readFileSync(path, 'utf8')) as Partial<GrpcServerConfig>;
  if (!cfg.cert || !cfg.token) throw new BridgeSecurityError(`${path} has no certificate or token`);
  if (!cfg.fileSocketPath) throw new BridgeSecurityError(`${path} announces a TCP port only; the Manager requires the Unix socket used on Linux and macOS`);
  return { port: cfg.port ?? 0, cert: cfg.cert, token: cfg.token, fileSocketPath: cfg.fileSocketPath };
}

/** The socket must be a socket, owned by Bridge's user, in a directory others cannot tamper with. */
export function checkSocket(path: string, opts: TrustOptions = {}): void {
  const uid = expectedUid(opts);
  const st = lstatSync(path);
  if (!st.isSocket()) throw new BridgeSecurityError(`${path} is not a Unix socket`);
  if (uid !== undefined && st.uid !== uid) throw new BridgeSecurityError(`Socket ${path} is owned by uid ${st.uid}, expected ${uid}`);
  checkDir(dirname(path), uid, 'Socket directory');
}

// ---------------------------------------------------------------------------- client

type Unary<Req, Res> = (req: Req, meta: grpc.Metadata, opts: grpc.CallOptions, cb: (err: grpc.ServiceError | null, res: Res) => void) => grpc.ClientUnaryCall;

let definition: grpc.GrpcObject | undefined;
function loadDefinition(): grpc.GrpcObject {
  if (!definition) {
    let file = PROTO;
    try {
      statSync(file);
    } catch {
      file = PROTO_SRC; // running from dist/: the .proto stays in src/
    }
    const pkg = protoLoader.loadSync(file, { keepCase: true, longs: Number, enums: String, defaults: true, oneofs: true, includeDirs: [join(dirname(file))] });
    definition = grpc.loadPackageDefinition(pkg);
  }
  return definition;
}

const b64 = (secret: string) => Buffer.from(Buffer.from(secret, 'utf8').toString('base64'), 'utf8');

export class BridgeClient extends EventEmitter {
  private readonly client: grpc.Client & Record<string, Unary<unknown, unknown>>;
  private readonly token: string;
  private stream?: grpc.ClientReadableStream<Record<string, unknown>>;
  private closed = false;

  private constructor(cfg: GrpcServerConfig, private readonly timeoutMs: number) {
    super();
    const Bridge = (loadDefinition().grpc as grpc.GrpcObject).Bridge as grpc.ServiceClientConstructor;
    // The certificate is self-signed and published by Bridge in its 0700 settings directory:
    // it is the only trusted root, and the presented certificate must be exactly that one.
    const pinned = new X509Certificate(cfg.cert).fingerprint256;
    const creds = grpc.credentials.createSsl(Buffer.from(cfg.cert), null, null, {
      checkServerIdentity: (_host, cert) =>
        cert.fingerprint256 === pinned ? undefined : new BridgeSecurityError('Bridge presented a certificate that differs from grpcServerConfig.json')
    });
    this.client = new Bridge(`unix://${cfg.fileSocketPath}`, creds, {
      'grpc.max_receive_message_length': 4 * 1024 * 1024
    }) as unknown as BridgeClient['client'];
    this.token = cfg.token;
  }

  /** Connect to the Bridge whose settings live in `settingsDir` ($XDG_CONFIG_HOME/protonmail/bridge-v3). */
  static async connect(settingsDir: string, opts: TrustOptions & { timeoutMs?: number } = {}): Promise<BridgeClient> {
    const cfg = readServerConfig(join(settingsDir, 'grpcServerConfig.json'), opts);
    checkSocket(cfg.fileSocketPath, opts);
    const client = new BridgeClient(cfg, opts.timeoutMs ?? 10_000);
    await new Promise<void>((resolve, reject) =>
      client.client.waitForReady(Date.now() + (opts.timeoutMs ?? 10_000), err => (err ? reject(new Error(`Cannot reach Bridge on ${cfg.fileSocketPath}: ${err.message}`)) : resolve()))
    );
    return client;
  }

  private meta(): grpc.Metadata {
    const m = new grpc.Metadata();
    m.set('server-token', this.token);
    return m;
  }

  private call<Res>(method: string, req: unknown = {}): Promise<Res> {
    return new Promise((resolve, reject) => {
      const fn = this.client[method];
      if (typeof fn !== 'function') return reject(new Error(`Unknown Bridge method ${method}`));
      fn.call(this.client, req, this.meta(), { deadline: Date.now() + this.timeoutMs }, (err, res) => {
        if (err) reject(new Error(`Bridge ${method} failed: ${err.details || err.message}`));
        else resolve(res as Res);
      });
    });
  }

  // ---------------------------------------------------------------- read-only

  async version(): Promise<string> {
    return (await this.call<{ value: string }>('Version')).value;
  }

  async os(): Promise<string> {
    return (await this.call<{ value: string }>('GoOs')).value;
  }

  /** Tells Bridge a frontend is attached (required once before events are delivered). */
  async ready(): Promise<void> {
    await this.call('GuiReady');
  }

  async mailServerSettings(): Promise<MailServerSettings> {
    return this.call<MailServerSettings>('MailServerSettings');
  }

  async keychains(): Promise<{ current: string; available: string[] }> {
    const [current, available] = await Promise.all([
      this.call<{ value: string }>('CurrentKeychain'),
      this.call<{ keychains: string[] }>('AvailableKeychains')
    ]);
    return { current: current.value, available: available.keychains };
  }

  async users(): Promise<BridgeUser[]> {
    const res = await this.call<{ users: Array<Record<string, unknown>> }>('GetUserList');
    return res.users.map(toUser);
  }

  async user(userId: string): Promise<BridgeUser> {
    return toUser(await this.call<Record<string, unknown>>('GetUser', { value: userId }));
  }

  /** Asynchronous in Bridge: completion and errors arrive as 'mailServer' events. */
  async setMailServerSettings(settings: MailServerSettings): Promise<void> {
    await this.call('SetMailServerSettings', settings);
  }

  async isPortFree(port: number): Promise<boolean> {
    return (await this.call<{ value: boolean }>('IsPortFree', { value: port })).value;
  }

  // ---------------------------------------------------------------- state-changing (callers check compatibility first)

  async login(username: string, password: string, useHvDetails = false): Promise<void> {
    await this.call('Login', { username, password: b64(password), ...(useHvDetails ? { useHvDetails: true } : {}) });
  }

  async login2fa(username: string, code: string): Promise<void> {
    await this.call('Login2FA', { username, password: b64(code) });
  }

  async login2passwords(username: string, mailboxPassword: string): Promise<void> {
    await this.call('Login2Passwords', { username, password: b64(mailboxPassword) });
  }

  async loginAbort(username: string): Promise<void> {
    await this.call('LoginAbort', { username });
  }

  async logoutUser(userId: string): Promise<void> {
    await this.call('LogoutUser', { value: userId });
  }

  async removeUser(userId: string): Promise<void> {
    await this.call('RemoveUser', { value: userId });
  }

  // ---------------------------------------------------------------- events

  /**
   * Open the event stream. Bridge accepts a single stream: if another frontend
   * (bridge-gui) is attached, this fails with ALREADY_EXISTS.
   */
  startEvents(): void {
    if (this.stream) return;
    const fn = (this.client as unknown as Record<string, (req: unknown, meta: grpc.Metadata) => grpc.ClientReadableStream<Record<string, unknown>>>).RunEventStream!;
    const stream = fn.call(this.client, { ClientPlatform: 'protonmail-pro-mcp bridge-manager' }, this.meta());
    this.stream = stream;
    stream.on('data', (raw: Record<string, unknown>) => {
      const event = toEvent(raw);
      if (event) this.emit('event', event);
    });
    stream.on('error', (err: grpc.ServiceError) => {
      if (this.stream === stream) this.stream = undefined;
      if (!this.closed && err.code !== grpc.status.CANCELLED) this.emit('streamError', new Error(err.code === grpc.status.ALREADY_EXISTS ? 'Another frontend (bridge-gui?) already holds the Bridge event stream' : err.details || err.message));
    });
    stream.on('end', () => {
      if (this.stream === stream) this.stream = undefined;
      if (!this.closed) this.emit('streamEnd');
    });
  }

  async close(): Promise<void> {
    if (this.closed) return;
    this.closed = true;
    const stream = this.stream;
    if (stream) {
      // Detach gracefully: cancelling the stream alone makes Bridge quit.
      await this.call('StopEventStream').catch(() => undefined);
      this.stream = undefined;
      stream.cancel();
    }
    this.client.close();
  }
}

// ---------------------------------------------------------------------------- decoding

function toUser(u: Record<string, unknown>): BridgeUser {
  return {
    id: String(u.id ?? ''),
    username: String(u.username ?? ''),
    state: (u.state as BridgeUserState) ?? 'SIGNED_OUT',
    splitMode: Boolean(u.splitMode),
    usedBytes: Number(u.usedBytes ?? 0),
    totalBytes: Number(u.totalBytes ?? 0),
    addresses: (u.addresses as string[] | undefined) ?? [],
    password: Buffer.isBuffer(u.password) ? u.password.toString('utf8') : String(u.password ?? '')
  };
}

type UsernameLoginEvent = Extract<BridgeEvent, { kind: 'login'; username: string }>['type'];

const LOGIN_USERNAME_EVENTS: Record<string, UsernameLoginEvent> = {
  tfaRequested: 'tfaRequested',
  twoPasswordRequested: 'twoPasswordRequested',
  fidoRequested: 'fidoRequested',
  tfaOrFidoRequested: 'tfaOrFidoRequested',
  loginFidoTouchRequested: 'fidoTouchRequested',
  loginFidoTouchCompleted: 'fidoTouchCompleted',
  loginFidoPinRequired: 'fidoPinRequired'
};

export function toEvent(raw: Record<string, unknown>): BridgeEvent | undefined {
  const family = raw.event as string | undefined;
  const body = family ? (raw[family] as Record<string, unknown>) : undefined;
  if (!family || !body) return undefined;
  const which = body.event as string | undefined;
  const e = which ? (body[which] as Record<string, unknown>) : undefined;
  if (family === 'genericError') return { kind: 'genericError', code: Number(body.code ?? 0) };
  if (!which || !e) return undefined;
  switch (family) {
    case 'login':
      if (which === 'error') return { kind: 'login', type: 'error', errorType: String(e.type), message: String(e.message ?? '') };
      if (which === 'finished' || which === 'alreadyLoggedIn') return { kind: 'login', type: which, userId: String(e.userID ?? ''), wasSignedOut: Boolean(e.wasSignedOut) };
      if (which === 'hvRequested') return { kind: 'login', type: 'hvRequested', hvUrl: String(e.hvUrl ?? '') };
      if (LOGIN_USERNAME_EVENTS[which]) return { kind: 'login', type: LOGIN_USERNAME_EVENTS[which]!, username: String(e.username ?? '') };
      return undefined;
    case 'user':
      if (which === 'userDisconnected') return { kind: 'user', type: 'disconnected', username: String(e.username ?? '') };
      if (which === 'imapLoginFailedEvent') return { kind: 'user', type: 'imapLoginFailed', username: String(e.username ?? '') };
      if (which === 'userBadEvent') return { kind: 'user', type: 'bad', userId: String(e.userID ?? ''), message: String(e.errorMessage ?? '') };
      if (which === 'syncProgressEvent') return { kind: 'user', type: 'syncProgress', userId: String(e.userID ?? ''), progress: Number(e.progress ?? 0), remainingMs: Number(e.remainingMs ?? 0) };
      {
        const map: Record<string, 'changed' | 'syncStarted' | 'syncFinished' | 'splitModeChanged'> = {
          userChanged: 'changed',
          syncStartedEvent: 'syncStarted',
          syncFinishedEvent: 'syncFinished',
          toggleSplitModeFinished: 'splitModeChanged'
        };
        return map[which] ? { kind: 'user', type: map[which]!, userId: String(e.userID ?? '') } : undefined;
      }
    case 'app':
      if (which === 'internetStatus') return { kind: 'app', type: 'internetStatus', connected: Boolean(e.connected) };
      if (which === 'allUsersLoaded') return { kind: 'app', type: 'allUsersLoaded' };
      return undefined;
    case 'keychain':
      return { kind: 'keychain', type: which as 'hasNoKeychain' };
    case 'mailServerSettings':
      if (which === 'error') return { kind: 'mailServer', type: 'error', errorType: String(e.type) };
      if (which === 'mailServerSettingsChanged') return { kind: 'mailServer', type: 'changed', settings: e.settings as MailServerSettings };
      if (which === 'changeMailServerSettingsFinished') return { kind: 'mailServer', type: 'changeFinished' };
      return undefined;
    default:
      return undefined;
  }
}
