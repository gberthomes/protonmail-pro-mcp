/**
 * Minimal structured logger.
 *
 * Everything goes to stderr: on the stdio transport stdout is the JSON-RPC
 * channel and must never carry anything else.
 */

type Level = 'debug' | 'info' | 'warn' | 'error';

const ORDER: Record<Level, number> = { debug: 10, info: 20, warn: 30, error: 40 };

function envLevel(): Level {
  const raw = (process.env.LOG_LEVEL ?? (process.env.DEBUG === 'true' ? 'debug' : 'info')).toLowerCase();
  return raw in ORDER ? (raw as Level) : 'info';
}

let threshold = ORDER[envLevel()];

function serialize(value: unknown): string {
  if (value instanceof Error) return value.stack ?? `${value.name}: ${value.message}`;
  if (typeof value === 'string') return value;
  try {
    return JSON.stringify(value);
  } catch {
    return String(value);
  }
}

function write(level: Level, scope: string, message: string, extra?: unknown): void {
  if (ORDER[level] < threshold) return;
  const line = `${new Date().toISOString()} ${level.toUpperCase().padEnd(5)} [${scope}] ${message}`;
  process.stderr.write(extra === undefined ? `${line}\n` : `${line} ${serialize(extra)}\n`);
}

export interface Logger {
  debug(message: string, extra?: unknown): void;
  info(message: string, extra?: unknown): void;
  warn(message: string, extra?: unknown): void;
  error(message: string, extra?: unknown): void;
}

export function createLogger(scope: string): Logger {
  return {
    debug: (m, e) => write('debug', scope, m, e),
    info: (m, e) => write('info', scope, m, e),
    warn: (m, e) => write('warn', scope, m, e),
    error: (m, e) => write('error', scope, m, e)
  };
}

export function setLogLevel(level: Level): void {
  threshold = ORDER[level];
}
