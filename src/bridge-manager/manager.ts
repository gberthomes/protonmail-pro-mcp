/**
 * Proton Bridge Manager: one runtime per Bridge instance (a client, its single
 * event stream, the sign-in controller), plus account lifecycle operations.
 *
 * The Manager must be the only frontend attached to an instance: Bridge
 * accepts a single event stream, so bridge-gui cannot run at the same time.
 */

import { createLogger } from '../logger.js';
import { AuthController, AuthError, type AuthOptions, type AuthSessionView } from './auth.js';
import { BridgeClient, type BridgeEvent, type BridgeUser, type MailServerSettings } from './client.js';
import { assertWritable } from './compat.js';
import { inspectInstance, type InstanceConfig, type InstanceReport } from './instance.js';

const log = createLogger('bridge-manager');
const audit = createLogger('audit');

export interface AccountView {
  id: string;
  username: string;
  state: BridgeUser['state'];
  addresses: string[];
  splitMode: boolean;
  usedBytes: number;
  totalBytes: number;
}

export interface AccountCredentials {
  /** IMAP/SMTP login: Bridge accepts any address of the account (the primary one is returned). */
  username: string;
  /** Generated by Bridge for this account only. Secret. */
  password: string;
  imap: { host: string; port: number; security: 'starttls' | 'tls' };
  smtp: { host: string; port: number; security: 'starttls' | 'tls' };
}

export type Actor = { sub: string; email?: string } | 'cli';

function actorName(a: Actor): string {
  return a === 'cli' ? `cli(uid ${process.getuid?.() ?? '?'})` : (a.email ?? a.sub);
}

export function toAccountView(u: BridgeUser): AccountView {
  return { id: u.id, username: u.username, state: u.state, addresses: u.addresses, splitMode: u.splitMode, usedBytes: u.usedBytes, totalBytes: u.totalBytes };
}

class InstanceRuntime {
  client?: BridgeClient;
  version?: string;
  auth?: AuthController;
  private connecting?: Promise<BridgeClient>;
  readonly listeners = new Set<(e: BridgeEvent) => void>();

  constructor(
    readonly config: InstanceConfig,
    private readonly authOptions: AuthOptions
  ) {}

  async connected(): Promise<BridgeClient> {
    if (this.client) return this.client;
    if (this.connecting) return this.connecting;
    this.connecting = (async () => {
      const client = await BridgeClient.connect(this.config.settingsDir, { uid: this.config.uid });
      try {
        this.version = await client.version();
        await client.ready();
      } catch (err) {
        await client.close();
        throw err;
      }
      this.auth = new AuthController(this.config.id, client, this.authOptions);
      client.on('event', (e: BridgeEvent) => {
        this.auth?.handleEvent(e);
        for (const l of this.listeners) l(e);
      });
      const drop = (reason: string) => {
        log.warn(`Instance ${this.config.id}: ${reason}`);
        void this.auth?.abortAll(reason);
        if (this.client === client) {
          this.client = undefined;
          this.streaming = false;
        }
        void client.close();
      };
      client.on('streamError', (err: Error) => drop(`event stream failed: ${err.message}`));
      client.on('streamEnd', () => drop('event stream ended (Bridge stopped?)'));
      this.client = client;
      log.info(`Connected to Bridge ${this.version} (instance ${this.config.id})`);
      return client;
    })().finally(() => {
      this.connecting = undefined;
    });
    return this.connecting;
  }

  /**
   * Attach to Bridge's (single) event stream. Needed for sign-ins and live
   * updates only: read-only commands work while another Manager holds it.
   */
  async withEvents(): Promise<BridgeClient> {
    const client = await this.connected();
    if (!this.streaming) {
      const failed = new Promise<Error>(resolve => client.once('streamError', resolve));
      client.startEvents();
      // ALREADY_EXISTS comes back almost immediately when another frontend is attached.
      const err = await Promise.race([failed, new Promise<undefined>(r => setTimeout(() => r(undefined), 300))]);
      if (err) throw new AuthError(409, 'stream-busy', err.message);
      this.streaming = true;
    }
    return client;
  }

  private streaming = false;

  async close(): Promise<void> {
    this.streaming = false;
    await this.auth?.abortAll('Manager shutting down');
    await this.client?.close();
    this.client = undefined;
  }
}

export class BridgeManager {
  private readonly runtimes = new Map<string, InstanceRuntime>();

  constructor(
    instances: InstanceConfig[],
    private readonly options: { allowUntested?: boolean; auth?: AuthOptions } = {}
  ) {
    for (const i of instances) this.runtimes.set(i.id, new InstanceRuntime(i, options.auth ?? {}));
  }

  instances(): InstanceConfig[] {
    return [...this.runtimes.values()].map(r => r.config);
  }

  private runtime(id: string): InstanceRuntime {
    const r = this.runtimes.get(id);
    if (!r) throw new AuthError(404, 'unknown-instance', `Unknown Bridge instance "${id}"`);
    return r;
  }

  /** Read-only inspection (uses its own short connection; does not disturb the event stream). */
  inspect(id: string, opts?: { checkBinary?: boolean }): Promise<InstanceReport> {
    return inspectInstance(this.runtime(id).config, opts);
  }

  /** Subscribe to normalised Bridge events of an instance (connects if needed). */
  async onEvents(id: string, listener: (e: BridgeEvent) => void): Promise<() => void> {
    const r = this.runtime(id);
    await r.withEvents();
    r.listeners.add(listener);
    return () => r.listeners.delete(listener);
  }

  async accounts(id: string): Promise<AccountView[]> {
    const client = await this.runtime(id).connected();
    return (await client.users()).map(toAccountView);
  }

  async account(id: string, accountId: string): Promise<AccountView> {
    return toAccountView(await this.findUser(id, accountId));
  }

  private async findUser(id: string, accountId: string): Promise<BridgeUser> {
    const client = await this.runtime(id).connected();
    const users = await client.users();
    const key = accountId.toLowerCase();
    const u = users.find(x => x.id === accountId || x.username.toLowerCase() === key || x.addresses.some(a => a.toLowerCase() === key));
    if (!u) throw new AuthError(404, 'unknown-account', `No account "${accountId}" on instance ${id}`);
    return u;
  }

  async mailServer(id: string): Promise<MailServerSettings> {
    return (await this.runtime(id).connected()).mailServerSettings();
  }

  /** IMAP/SMTP settings of one account. Returns a secret: callers decide who may see it. */
  async credentials(id: string, accountId: string, actor: Actor): Promise<AccountCredentials> {
    const r = this.runtime(id);
    const client = await r.connected();
    const [u, mail] = await Promise.all([this.findUser(id, accountId), client.mailServerSettings()]);
    if (u.state !== 'CONNECTED') throw new AuthError(409, 'not-connected', `Account ${u.username} is ${u.state}: sign in again first`);
    audit.info(`credentials of ${u.username} (${u.id}) on ${id} read by ${actorName(actor)}`);
    return {
      username: u.addresses[0] ?? u.username,
      password: u.password,
      imap: { host: '127.0.0.1', port: mail.imapPort, security: mail.useSSLForImap ? 'tls' : 'starttls' },
      smtp: { host: '127.0.0.1', port: mail.smtpPort, security: mail.useSSLForSmtp ? 'tls' : 'starttls' }
    };
  }

  /** All connected accounts with their credentials (for the MCP mail layer). Secret. */
  async connectedCredentials(id: string): Promise<Array<AccountView & { credentials: AccountCredentials }>> {
    const r = this.runtime(id);
    const client = await r.connected();
    const [users, mail] = await Promise.all([client.users(), client.mailServerSettings()]);
    return users
      .filter(u => u.state === 'CONNECTED' && u.addresses.length > 0)
      .map(u => ({
        ...toAccountView(u),
        credentials: {
          username: u.addresses[0]!,
          password: u.password,
          imap: { host: '127.0.0.1', port: mail.imapPort, security: mail.useSSLForImap ? ('tls' as const) : ('starttls' as const) },
          smtp: { host: '127.0.0.1', port: mail.smtpPort, security: mail.useSSLForSmtp ? ('tls' as const) : ('starttls' as const) }
        }
      }));
  }

  // ------------------------------------------------------------------ state-changing

  private async writable(id: string): Promise<InstanceRuntime> {
    const r = this.runtime(id);
    await r.withEvents();
    assertWritable(r.version, Boolean(this.options.allowUntested));
    return r;
  }

  async startSignIn(id: string, username: string, password: string, actor: Actor): Promise<AuthSessionView> {
    const r = await this.writable(id);
    audit.info(`sign-in of ${username.trim()} on ${id} started by ${actorName(actor)}`);
    return r.auth!.start(username, password);
  }

  /** The controller of an instance, for the next steps of a sign-in. */
  async signIn(id: string): Promise<AuthController> {
    const r = await this.writable(id);
    return r.auth!;
  }

  async logout(id: string, accountId: string, actor: Actor): Promise<void> {
    const r = await this.writable(id);
    const u = await this.findUser(id, accountId);
    await r.client!.logoutUser(u.id);
    audit.info(`account ${u.username} (${u.id}) signed out on ${id} by ${actorName(actor)}`);
  }

  /** Remove an account from Bridge (its local data is deleted by Bridge). `confirm` must repeat the username. */
  async remove(id: string, accountId: string, confirm: string, actor: Actor): Promise<void> {
    const r = await this.writable(id);
    const u = await this.findUser(id, accountId);
    const typed = confirm.trim().toLowerCase();
    if (!typed || (typed !== u.username.toLowerCase() && !u.addresses.some(a => a.toLowerCase() === typed))) {
      throw new AuthError(400, 'confirmation-required', `Type the account username (${u.username}) or one of its addresses to confirm its removal`);
    }
    await r.client!.removeUser(u.id);
    audit.info(`account ${u.username} (${u.id}) removed from ${id} by ${actorName(actor)}`);
  }

  /**
   * Change the IMAP/SMTP ports of an instance (each instance on a host needs
   * its own). Bridge applies it asynchronously and reports errors as events.
   */
  async setPorts(id: string, ports: { imapPort: number; smtpPort: number }, actor: Actor): Promise<MailServerSettings> {
    for (const p of [ports.imapPort, ports.smtpPort]) {
      if (!Number.isInteger(p) || p < 1024 || p > 65535) throw new AuthError(400, 'invalid-port', 'Ports must be between 1024 and 65535');
    }
    if (ports.imapPort === ports.smtpPort) throw new AuthError(400, 'invalid-port', 'IMAP and SMTP need different ports');
    const r = await this.writable(id);
    const client = r.client!;
    const current = await client.mailServerSettings();
    const errors: string[] = [];
    const done = new Promise<void>((resolve, reject) => {
      const timer = setTimeout(() => (r.listeners.delete(listener), reject(new Error('Bridge did not confirm the change in time'))), 30_000);
      const listener = (e: BridgeEvent) => {
        if (e.kind !== 'mailServer') return;
        if (e.type === 'error') errors.push(e.errorType);
        if (e.type === 'changeFinished') {
          clearTimeout(timer);
          r.listeners.delete(listener);
          resolve();
        }
      };
      r.listeners.add(listener);
    });
    await client.setMailServerSettings({ ...current, imapPort: ports.imapPort, smtpPort: ports.smtpPort });
    await done;
    const after = await client.mailServerSettings();
    audit.info(`ports of ${id} set to IMAP ${after.imapPort} / SMTP ${after.smtpPort} by ${actorName(actor)}${errors.length ? ` (errors: ${errors.join(', ')})` : ''}`);
    if (errors.length) throw new AuthError(409, 'port-change-failed', `Bridge refused the change: ${errors.join(', ')} (port in use?)`);
    return after;
  }

  async close(): Promise<void> {
    await Promise.all([...this.runtimes.values()].map(r => r.close()));
  }
}
